#!/usr/bin/env bash
# Configure omnifocus-cli for the Omni Sync Server on this machine.
#
#   scripts/setup-omni-sync.sh                      # prompt for the Omni Account
#   OF_OP_ITEM="op://Vault/Item" scripts/setup-omni-sync.sh   # read it from 1Password
#
# Writes ~/.config/omnifocus-cli/credentials.env (mode 0600) with the sync URL,
# account, the regional shard it redirects to, and OF_TIMEZONE, then prints MCP
# client snippets.  Nothing is written to the sync server.
#
# Environment:
#   OF_OP_ITEM       1Password item reference with "username" and "password" fields
#   OF_ENV_FILE      output path (default ~/.config/omnifocus-cli/credentials.env)
#   OF_TIMEZONE      IANA zone for "today" (default: this machine's zone)
#   OF_REPO_REF      git ref used in the uvx snippet (default feat/oss-perspectives)
set -euo pipefail

env_file="${OF_ENV_FILE:-$HOME/.config/omnifocus-cli/credentials.env}"
repo_ref="${OF_REPO_REF:-feat/oss-perspectives}"
repo_url="https://github.com/tauto1127/OmniFocus-CLI"

if [[ -n "${OF_OP_ITEM:-}" ]]; then
  command -v op >/dev/null || { echo "op (1Password CLI) not found" >&2; exit 1; }
  user="$(op read "$OF_OP_ITEM/username")"
  pass="$(op read "$OF_OP_ITEM/password")"
else
  read -r -p "Omni Account username: " user
  read -r -s -p "Omni Account password: " pass; echo
fi
[[ -n "$user" && -n "$pass" ]] || { echo "username/password missing" >&2; exit 1; }

tz="${OF_TIMEZONE:-}"
if [[ -z "$tz" ]]; then
  tz="$(timedatectl show -p Timezone --value 2>/dev/null || true)"
  [[ -z "$tz" && -L /etc/localtime ]] && tz="$(readlink /etc/localtime | sed 's#.*/zoneinfo/##')"
  [[ -z "$tz" ]] && tz="UTC"
fi

user_path="$(python3 -c 'import sys,urllib.parse;print(urllib.parse.quote(sys.argv[1],safe=""))' "$user")"
base="https://sync.omnigroup.com/$user_path/OmniFocus.ofocus/"

# The account is served from a shard (sync<N>.omnigroup.com or <name>.sync.omnigroup.com).
redirect="$(curl -s -o /dev/null -w '%{redirect_url}' -X PROPFIND -H 'Depth: 0' "$base" || true)"
shard="$(printf '%s' "$redirect" | sed -nE 's#^(https://[a-z0-9.-]+\.omnigroup\.com)/.*#\1#p')"
if [[ -z "$shard" ]]; then
  echo "warning: no shard redirect seen; using sync.omnigroup.com directly" >&2
fi

# Verify the account (Digest auth) before writing anything.
probe="${shard:-https://sync.omnigroup.com}/$user_path/OmniFocus.ofocus/"
code="$(curl -s -o /dev/null -w '%{http_code}' --digest -u "$user:$pass" -X PROPFIND -H 'Depth: 0' "$probe")"
if [[ "$code" != "207" ]]; then
  echo "Omni Sync Server login failed (HTTP $code). Check the account." >&2
  exit 1
fi

mkdir -p "$(dirname "$env_file")"
umask 077
if [[ -f "$env_file" ]]; then
  cp -p "$env_file" "$env_file.bak-$(date +%Y%m%d%H%M%S)"
fi
{
  echo "# Omni Sync Server (generated by setup-omni-sync.sh)"
  echo "OF_WEBDAV_URL=$base"
  echo "OF_WEBDAV_USER=$user"
  echo "OF_WEBDAV_PASS=$pass"
  [[ -n "$shard" ]] && echo "OF_WEBDAV_TRUSTED_REDIRECT_ORIGINS=$shard"
  echo "OF_TIMEZONE=$tz"
} > "$env_file"
chmod 600 "$env_file"
echo "Wrote $env_file (shard: ${shard:-none}, timezone: $tz)"

cat <<EOF

Next steps
----------
CLI (needs uv):
  set -a; . $env_file; set +a
  uvx --from git+$repo_url@$repo_ref of perspective Forecast

MCP over stdio (Claude Desktop / Claude Code / Cursor ...):
  {
    "mcpServers": {
      "omnifocus": {
        "command": "bash",
        "args": ["-c", "set -a; . $env_file; set +a; exec uvx --from git+$repo_url@$repo_ref of-mcp"],
        "env": {"OF_MCP_TOOLSET": "core"}
      }
    }
  }
  Claude Code one-liner:
  claude mcp add omnifocus -e OF_MCP_TOOLSET=core -- bash -c 'set -a; . $env_file; set +a; exec uvx --from git+$repo_url@$repo_ref of-mcp'

Drop OF_MCP_TOOLSET=core to expose every tool (better for large models).
EOF
